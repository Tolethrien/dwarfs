import { BUILD_SPACE, CAMP_STORE, MINE_SHAFT, WORLD } from "./sceneData";
import World from "./world/world";
import { shaftColumns } from "./world/shaftShape";
import Shaft from "./actors/shaft";
import { generateMap, MAP_GEN } from "./mapGen/mapGen";

export function startGame(seed: number) {
  const scene = Pragma.addScene("game");
  const world = new World(MAP_GEN.world);
  generateMap(world, seed);
  scene.sharedData.add(WORLD, world);
  scene.sharedData.add(CAMP_STORE, new Stock(STORAGE.start));
  scene.sharedData.add(BUILD_SPACE, new BuildSpace(MAP_GEN.world.tileInPixels));
  // made before the systems, the intro puts it on the scene
  const shaft = new Shaft({ position: { x: shaftColumns(world).from * MAP_GEN.world.tileInPixels, y: 0 }, seed: seed });
  scene.sharedData.add(MINE_SHAFT, shaft);

  scene.addSystem(GameEvents);
  scene.addSystem(GameMode);
  scene.addSystem(Calendar);
  scene.addSystem(Terrain);
  scene.addSystem(MapView);
  scene.addSystem(Decos);
  scene.addSystem(Vfx);
  scene.addSystem(Sounds);
  scene.addSystem(PlayerStats);
  scene.addSystem(BallPhysics);
  scene.addSystem(Biomes);
  scene.addSystem(Discovery);
  scene.addSystem(Director);
  scene.addSystem(Buffs);
  scene.addSystem(Workforce);
  scene.addSystem(Roster);
  scene.addSystem(Inbox);
  scene.addSystem(Rails);
  scene.addSystem(Transport);
  scene.addSystem(Stations);
  scene.addSystem(Buildings);
  scene.addSystem(Conditions);
  scene.addSystem(GameUI);
  scene.addSystem(BuildMode);
  scene.addSystem(ShootMode);
  scene.addSystem(StoryEvents, shaft);
  scene.addSystem(Profiler);
}
